"""Sync the pinned, generated NewsNow catalog without fetching or inventing sources."""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATEGORIES = {'china': '国内', 'world': '国际', 'tech': '科技', 'finance': '财经', 'sports': '体育'}


def main():
    upstream = ROOT / 'vendor/newsnow'
    sources = json.loads((upstream / 'shared/sources.json').read_text())
    catalog, metadata = [], {}
    icons = ROOT / 'frontend/public/assets/newsnow'
    icons.mkdir(parents=True, exist_ok=True)
    for sid, source in sources.items():
        if source.get('redirect') or source.get('disable') is True:
            continue
        # Missing type means a normal timeline. "cf" only excludes Cloudflare deployment.
        catalog.append(dict(id=sid, name=source['name'], title=source.get('title', ''),
                            category=CATEGORIES[source['column']], mode=source.get('type', 'realtime'),
                            interval_seconds=max(60, source['interval'] // 1000)))
        metadata[sid] = {key: source.get(key, '') for key in ('name', 'title', 'color', 'home')}
        icon = sid.split('-')[0] + '.png'
        shutil.copyfile(upstream / 'public/icons' / icon, icons / icon)
    shutil.copyfile(upstream / 'LICENSE', icons / 'LICENSE.txt')
    (ROOT / 'trendradar/workbench/newsnow_catalog.json').write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + '\n')
    (ROOT / 'frontend/src/components/newsnowSources.ts').write_text(
        '// Generated by scripts/sync_newsnow_catalog.py from the pinned NewsNow catalog.\n'
        '// Copyright (c) 2024 ourongxing. MIT: /assets/newsnow/LICENSE.txt\n'
        'export const newsnowSources: Record<string, {name: string; title: string; color: string; home: string}> = '
        + json.dumps(metadata, ensure_ascii=False, indent=2) + ';\n')
    print(f'Synced {len(catalog)} canonical channels; {len(sources) - len(catalog)} aliases omitted.')


if __name__ == '__main__':
    main()
